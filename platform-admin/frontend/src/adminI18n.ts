export type AdminCopy = (typeof ADMIN_COPY)[AdminLocale];

export function resolveAdminLocale(): AdminLocale {
  if (typeof window !== "undefined") {
    const saved = window.localStorage.getItem(ADMIN_LOCALE_STORAGE_KEY);
    if (saved === "en" || saved === "zh-CN") {
      return saved;
    }
    if (window.navigator.language.toLowerCase().startsWith("zh")) {
      return "zh-CN";
    }
  }
  return "en";
}
